USE qldatn_detai;

CREATE TABLE IF NOT EXISTS HoiDong (
    MaHoiDong INT PRIMARY KEY AUTO_INCREMENT,
    TenHoiDong VARCHAR(255) NOT NULL,
    MaDeTai INT NOT NULL,
    NgayThanhLap DATE DEFAULT (CURRENT_DATE),
    FOREIGN KEY (MaDeTai) REFERENCES DeTai(MaDeTai)
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS ThanhVienHoiDong (
    MaThanhVien INT PRIMARY KEY AUTO_INCREMENT,
    MaHoiDong INT NOT NULL,
    MaGV VARCHAR(20) NOT NULL,
    VaiTro VARCHAR(50) NOT NULL DEFAULT 'UY_VIEN',
    FOREIGN KEY (MaHoiDong) REFERENCES HoiDong(MaHoiDong) ON DELETE CASCADE
) CHARACTER SET utf8mb4;
