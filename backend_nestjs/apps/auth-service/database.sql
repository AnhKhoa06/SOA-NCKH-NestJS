CREATE DATABASE IF NOT EXISTS qldatn_auth;
USE qldatn_auth;

CREATE TABLE TaiKhoan (
    IdTaiKhoan INT PRIMARY KEY AUTO_INCREMENT,
    TenDangNhap VARCHAR(100) NOT NULL UNIQUE,
    MatKhauBam VARCHAR(255) NOT NULL,
    VaiTro ENUM('QTV', 'GV', 'SV') NOT NULL,
    MaDinhDanh VARCHAR(20) NULL,          -- MaGV hoặc MaSV; QTV có thể NULL hoặc QTV001
    Email VARCHAR(255) NULL UNIQUE,
    TrangThai ENUM('HOAT_DONG', 'KHOA_TAM', 'NGUNG_HOAT_DONG') NOT NULL DEFAULT 'HOAT_DONG',
    BatBuocDoiMatKhau BOOLEAN NOT NULL DEFAULT FALSE,
    SoLanSai INT NOT NULL DEFAULT 0,
    KhoaDen DATETIME NULL,
    NgayTao DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE RefreshToken (
    IdRefreshToken INT PRIMARY KEY AUTO_INCREMENT,
    IdTaiKhoan INT NOT NULL,
    TokenBam VARCHAR(255) NOT NULL,
    HetHan DATETIME NOT NULL,
    DaThuHoi BOOLEAN NOT NULL DEFAULT FALSE,
    NgayTao DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (IdTaiKhoan) REFERENCES TaiKhoan(IdTaiKhoan)
);
